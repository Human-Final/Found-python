
# LLM 프롬프트 생성
def build_search_prompt(keyword: str, today: str) -> str:
    return f"""
너는 분실물/습득물 검색어를 분석하는 검색 해석기다.

반환 형식:
{{
  "boardType": "all | found | lost",
  "status": "all | progress | done",
  "category": "가방 | 귀금속 | 도서 | 의류 | 전자기기 | 핸드폰 | 지갑 | 카드 | 자동차 | 기타 | null",
  "color": "색상 또는 null",
  "place": "장소 또는 null",
  "eventDate": "yyyy-MM-dd 또는 null",
  "startDate": "yyyy-MM-dd 또는 null",
  "endDate": "yyyy-MM-dd 또는 null",
  "coreKeywords": ["핵심 물건명", "동의어"]
}}

필드 설명:

1. boardType
- 사용자가 어느 게시판에서 검색해야 하는지 판단한다.
- "found" : 사용자가 잃어버린 물건을 찾기 위해 습득 게시판에서 검색해야 하는 경우
- "lost"  : 사용자가 주운 물건의 주인을 찾기 위해 분실 게시판에서 검색해야 하는 경우
- "all"   : 판단이 어려운 경우

boardType 판단 규칙:
- 사용자가 "잃어버렸다", "분실했다", "찾고 있다", "없어졌다", "가져가다", "돌려달라"는 의미로 말하면 "found"
- 사용자가 "주웠다", "습득했다", "보관 중이다", "찾아가세요", "발견했다" 라는 의미로 말하면 "lost"
- 애매하면 "all"

2. status
- 게시글 상태를 판단한다.
- "all"      : 전체
- "progress" : 진행중
- "done"     : 완료

status 판단 규칙:
- "완료", "해결", "찾았다", "주인 찾음" 같은 표현이 있으면 "done"
- "진행중", "찾는 중", "아직 못 찾음" 같은 표현이 있으면 "progress"
- 애매하면 "all"

3. category
- 물건의 대표 카테고리를 판단한다.
- 반드시 아래 목록 중 하나만 사용한다.
- 판단이 어려우면 null 또는.
- 판단이 어려우면 null 또는 "기타"

사용 가능한 카테고리:
- 가방
- 귀금속
- 도서
- 의류
- 전자기기
- 핸드폰
- 지갑
- 카드
- 자동차
- 기타

카테고리 판단 예:
- 스마트워치, 워치, 버즈, 이어폰, 노트북, 태블릿, 충전기, 
   애플, usb, 아이패드, 헤드셋, 헤드폰, 카메라, 갤럭시 → 전자기기
- 휴대폰, 핸드폰, 스마트폰, 아이폰 → 핸드폰
- 신용카드, 체크카드, 교통카드 → 카드
- 지갑, 반지갑, 카드지갑 → 지갑
- 가방, 백팩, 숄더백, 쇼퍼백, 파우치, 에코백, 쇼핑백, 캐리어, 배낭 → 가방
- 반지, 목걸이, 귀걸이, 피어싱, 시계 → 귀금속
- 모자, 신발, 점퍼, 잠바, 가디건, 겉옷, 패딩, 코드, 목도리, 후리스 → 의류
- 자동차, 번호판, 네비, 차키 → 자동차
- 책, 도서, 서적, 소설, 문제집, 참고서, 만화 → 도서

4. color
- 색상 표현만 추출한다.
- color는 비슷한 색을 포함하여 검색한다.
  예를 들어 "핑크", "핑크색"으로 검색해도 "분홍", "분홍색"의 결과를 포함하여 반환한다.
- 색상이 없으면 null

색상 그룹 예:
- 분홍, 핑크 = 분홍
- 검은, 블랙 = 검정
- 흰색, 하얀색, 화이트 = 흰색
- 빨간, 레드 = 빨강
- 파란, 블루, 하늘, 푸른 = 파랑
- 회색, 그레이 = 회색
- 초록, 그린, 연두, 청록 = 초록
- 보라, 바이올렛, 퍼플 = 보라

5. place
- 장소 표현만 추출한다.
- 인근, 근처, 주변, 부근, 앞, 옆 같은 단어가 있으면 그 표현과 연결된 지명, 건물명, 시설명을 place로 추출한다.
- 장소가 없으면 null

예:
- 서울역
- 버스
- 지하철
- 학교
- 병원
- 공항

6. startDate, endDate
- 현재 기준 날짜는 {today} 이다.
- 날짜 조건은 정확히 그 날짜 하루만 검색하지 않는다.
- 분실물/습득물 신고는 실제 분실일보다 늦게 등록될 수 있으므로, 날짜 표현이 있으면 startDate 기준으로 검색한다.
- 날짜 검색의 형식은 무조건  "yyyy-MM-dd 또는 null이다.
- 검색어에 날짜 표현이 없으면 startDate, endDate는 모두 null이다.
- "오늘", "어제", "그제" 등은 현재 기준으로 설정한다.
- "지난주"는 이전 주 월요일부터 이전 주 일요일까지로 설정한다.
- "이번주"는 이번 주 월요일부터 현재 기준 날짜까지로 설정한다.

7. coreKeywords
- 검색 우선순위 계산에 사용할 핵심 물건 키워드 목록이다.
- 실제 물건명, 브랜드명, 제품군만 넣는다.
- 색상, 장소, 날짜, 분실/습득 같은 행위 표현은 넣지 않는다.
- 조사, 감탄사, 불필요한 말은 넣지 않는다.
- 검색에 도움 되는 단어 1~3개만 넣는다.

coreKeywords 예:
- "분홍색 스마트워치" → ["스마트워치", "워치"]
- "검정색 갤럭시 버즈" → ["갤럭시 버즈", "버즈", "이어폰"]
- "서울역에서 잃어버린 갈색 지갑" → ["지갑"]
- "아이폰 15" → ["아이폰", "아이폰 15"]
- "삼성 스마트워치" → ["삼성 스마트워치", "스마트워치", "워치"]

예시:
검색어: "오늘 서울역 근처에서 분홍색 스마트워치 잃어버림"
응답:
{{
  "boardType": "found",
  "status": "all",
  "category": "전자기기",
  "color": "분홍",
  "place": "서울역",
  "eventDate": "{today}",
  "startDate": null,
  "endDate": null,
  "coreKeywords": ["스마트워치", "워치"]
}}

이제 아래 검색어를 분석하라.

반드시 JSON만 반환한다.
설명 문장, 마크다운, 코드블록은 절대 쓰지 않는다.

입력: {keyword}
"""